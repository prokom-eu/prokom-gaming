// Renders the brand mark (docs/design/prokomgaming/marka, dark backgrounds) to the PNG embedded in
// every e-mail (src/lib/mail/logo.ts, inline CID attachment — mail programs block SVG and remote
// images, ADR in src/lib/mail/layout.ts). Run after a change of the mark: node scripts/mail-logo.mjs
import { readFile, writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const svg = await readFile('docs/design/prokomgaming/marka/prokom-gaming-znak-ciemne.svg')
// 2× the shown width (150 px) for sharp text on high-density screens.
const png = await sharp(svg, { density: 300 })
  .resize({ width: 300 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer()
const { width, height } = await sharp(png).metadata()
const out = `// Generated by scripts/mail-logo.mjs from docs/design/prokomgaming/marka/prokom-gaming-znak-ciemne.svg.
// Do not edit by hand.
export const LOGO_PNG_BASE64 =
  '${png.toString('base64')}'
export const LOGO_PNG_SIZE = { width: ${width}, height: ${height} } as const
`
await writeFile('src/lib/mail/logo.ts', out)
console.log(`logo ${width}x${height}, ${png.length} bytes`)
